"""Builds the light (ESL) Valhalla Combat plugin from the Spriggit export of the original ValhallaCombat.esp (esp/ValhallaCombat).

What it does, working on a copy in esp-esl/:
  1. (no Backstab Bug Fix: Moonling's "Valhalla Combat - Backstab Bug Fix", Nexus 97195, stays a separate recommended mod);
  2. drops the MCM Helper quest (ValhallaCombat_MCM_Quest), the only record that needs SkyUI, and the two masters SkyUI_SE.esp and MCMHelper.esp;
  3. renumbers every new record into 000800.. and writes the old -> new map (esl/map_valhalla.json and src/include/FormIdMap.h, used by the DLL
     so Killmoves.ini and other files that name the old FormIDs keep working);
  4. sets the light flag and deserializes with Spriggit to release-contents/ValhallaCombat.esp.

Usage: python tools/esl_build.py        (needs tools/spriggit-cli.sh of the Claude toolkit; see SPRIGGIT below)
"""
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "esp", "ValhallaCombat")
WORK = os.path.join(HERE, "esp-esl", "ValhallaCombat")
OUT = os.path.join(HERE, "release-contents", "ValhallaCombat.esp")
SPRIGGIT = r"E:\Tabula Rasa\mods\Skyrim-Claude Code Modder's Toolkit\tools\spriggit-cli.sh"
SUFFIX = "_ValhallaCombat.esp.yaml"
FIRST = 0x800
LAST = 0xFFF

if os.path.exists(WORK):
    shutil.rmtree(WORK)
shutil.copytree(SRC, WORK)

# 1. (the Backstab Bug Fix by Moonling is not built in: it is a separate recommended mod, Nexus 97195)

# 2. MCM Helper quest and masters
quest = [f for f in os.listdir(os.path.join(WORK, "Quests")) if f.startswith("ValhallaCombat_MCM_Quest")]
assert len(quest) == 1, quest
os.remove(os.path.join(WORK, "Quests", quest[0]))
if not os.listdir(os.path.join(WORK, "Quests")):
    os.rmdir(os.path.join(WORK, "Quests"))

# 3. renumber
files = []
for root, _, names in os.walk(WORK):
    for n in names:
        if n.endswith(SUFFIX):
            files.append(os.path.join(root, n))
old_ids = sorted({re.search(r"- ([0-9A-F]{6})" + re.escape(SUFFIX), f).group(1) for f in files})
if FIRST + len(old_ids) - 1 > LAST:
    sys.exit(f"{len(old_ids)} new records do not fit the light plugin range")
mapping = {old: f"{FIRST + i:06X}" for i, old in enumerate(old_ids)}
mapping.pop("000D62", None)  # the removed quest
pattern = re.compile(r"\b([0-9A-F]{6}):ValhallaCombat\.esp")


def remap(text):
    def sub(m):
        old = m.group(1)
        if old not in mapping:
            sys.exit(f"reference to {old}:ValhallaCombat.esp which has no new id")
        return f"{mapping[old]}:ValhallaCombat.esp"

    return pattern.sub(sub, text)


for root, _, names in os.walk(WORK):
    for n in names:
        if not n.endswith(".yaml"):
            continue
        p = os.path.join(root, n)
        text = open(p, encoding="utf-8").read()
        new_text = remap(text)
        new_name = n
        m = re.search(r"- ([0-9A-F]{6})" + re.escape(SUFFIX), n)
        if m:
            new_name = n.replace(f"- {m.group(1)}{SUFFIX}", f"- {mapping[m.group(1)]}{SUFFIX}")
        if new_text != text:
            open(p, "w", encoding="utf-8", newline="\n").write(new_text)
        if new_name != n:
            os.rename(p, os.path.join(root, new_name))

# header: masters, light flag
rd = os.path.join(WORK, "RecordData.yaml")
text = open(rd, encoding="utf-8").read()
for master in ("SkyUI_SE.esp", "MCMHelper.esp"):
    block = f"  - Master: {master}\n    FileSize: 0\n"
    assert block in text, master
    text = text.replace(block, "")
assert "ModHeader:\n" in text and "  Flags:" not in text
text = text.replace("ModHeader:\n", "ModHeader:\n  Flags:\n  - Small\n", 1)
open(rd, "w", encoding="utf-8", newline="\n").write(text)

# map files
os.makedirs(os.path.join(HERE, "esl"), exist_ok=True)
json.dump(mapping, open(os.path.join(HERE, "esl", "map_valhalla.json"), "w"), indent=0)
with open(os.path.join(HERE, "src", "include", "FormIdMap.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/esl_build.py: old -> new local FormID of every record the light ValhallaCombat.esp renumbered. Do not edit by hand.\n#pragma once\n\n")
    f.write("#include <cstdint>\n\nnamespace VCIds\n{\n\tstruct Pair { std::uint32_t oldId; std::uint32_t newId; };\n\tinline constexpr Pair kMap[] = {\n")
    for old, new in sorted(mapping.items()):
        f.write(f"\t\t{{ 0x{old}, 0x{new} }},\n")
    f.write("\t};\n}\n")

# 4. build the plugin
os.makedirs(os.path.dirname(OUT), exist_ok=True)
if os.path.exists(OUT):
    os.remove(OUT)
r = subprocess.run(["bash", SPRIGGIT.replace("\\", "/"), "deserialize", "--InputPath", WORK.replace("\\", "/"), "--OutputPath", OUT.replace("\\", "/")],
                   capture_output=True, text=True)
tail = (r.stdout + r.stderr).strip().splitlines()[-3:]
print("\n".join(tail))
if not os.path.exists(OUT):
    sys.exit("deserialize failed")
print(f"{len(mapping)} records renumbered into {FIRST:06X}-{FIRST + len(mapping) - 1:06X}; wrote {OUT} ({os.path.getsize(OUT)} bytes)")
