"""Writes src/include/MenuTable.h: the settings of Valhalla Combat's MCM Helper menu as data for the SKSE Menu Framework pages in menu.cpp.

Inputs (from Valhalla Combat by dTry, BSD 3-Clause; the MCM config is part of the mod's download):
  MCM/Config/ValhallaCombat/config.json      pages, controls, ranges and the group conditions (which control enables which)
  MCM/Config/ValhallaCombat/settings.ini     the default of every setting
  Interface/Translations/ValhallaCombat_english.txt   labels and hover texts

Usage: python tools/gen_menu_table.py <folder that holds MCM/ and Interface/>
       (default: C:/Modlists/Tabula/mods/Valhalla Combat)
"""
import configparser
import json
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else r"C:\Modlists\Tabula\mods\Valhalla Combat"
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "src", "include", "MenuTable.h")

cfg = json.load(open(os.path.join(SRC, "MCM", "Config", "ValhallaCombat", "config.json"), encoding="utf-8"))
strings = {}
for line in open(os.path.join(SRC, "Interface", "Translations", "ValhallaCombat_english.txt"), encoding="utf-16").read().splitlines():
    if line.startswith("$") and "\t" in line:
        k, v = line.split("\t", 1)
        strings[k] = v.strip()
defaults = configparser.ConfigParser(inline_comment_prefixes=(";",))
defaults.optionxform = str
defaults.read(os.path.join(SRC, "MCM", "Config", "ValhallaCombat", "settings.ini"), encoding="utf-8")

HIDDEN = {"56A25": "TrueHudApi", "56A26": "TrueHudSpecialMeter", "56A23": "EldenCounterDamage", "56A24": "EldenCounterNpc"}


def text(key):
    if key is None:
        return ""
    if key not in strings:
        sys.exit(f"missing string {key}")
    t = re.sub(r"<[^>]+>", "", strings[key]).replace("\\n", " ").replace("&#13;", " ")
    return t.replace("\\", "\\\\").replace('"', '\\"')


def cstr(s):
    return '"' + s + '"'


def cond(item):
    """group condition -> (negated id, [or ids], [and ids], skip)"""
    gc = item.get("groupCondition")
    neg, ors, ands = 0, [], []
    if isinstance(gc, int):
        ands = [gc]
    elif isinstance(gc, dict):
        neg = gc.get("NOT", 0)
        ors = list(gc.get("OR", []))
        ands = list(gc.get("AND", []))
    if len(ors) > 3 or len(ands) > 3:
        sys.exit("group condition too long")
    pad = lambda a: (a + [0, 0, 0])[:3]
    return neg, pad(ors), pad(ands), 1 if item.get("groupBehavior") == "skip" else 0


KIND = {"header": "Header", "toggle": "Toggle", "slider": "Slider", "keymap": "Key", "enum": "Enum", "text": "Text", "hiddenToggle": "Hidden"}
out = []
pages = []
for pi, page in enumerate(cfg["pages"]):
    rows = []
    for it in page["content"]:
        t = it["type"]
        if t not in KIND:
            sys.exit(f"unhandled control type {t}")
        vo = it.get("valueOptions", {})
        key = section = ""
        if "id" in it:
            key, section = it["id"].split(":")
        dflt = 0.0
        if key:
            if not defaults.has_option(section, key):
                if t == "toggle":
                    dflt = 0.0
                elif t == "slider":
                    dflt = float(vo["min"])
                elif t == "keymap":
                    dflt = -1.0
            else:
                dflt = float(defaults.get(section, key))
        mn = float(vo.get("min", 0))
        mx = float(vo.get("max", 0))
        step = float(vo.get("step", 0))
        decimals = int(re.sub(r"[^0-9]", "", vo.get("formatString", "{0}")) or 0)
        label = text(it.get("text"))
        help_ = text(it.get("help")) if it.get("help") else ""
        if t == "text":
            label = text(it.get("text"))
            help_ = text(vo.get("value"))  # the text row carries its value text here; menu.cpp shows it next to the label
        options = ""
        nopts = 0
        if t == "enum":
            opts = [text(o) for o in vo["options"]]
            nopts = len(opts)
            options = "\\0".join(opts) + "\\0"
        ctrl = it.get("groupControl", 0)
        hidden = ""
        if t == "hiddenToggle":
            hidden = HIDDEN[vo["sourceForm"].split("|")[1]]
        neg, ors, ands, skip = cond(it)
        rows.append(
            f'\t{{ Kind::{KIND[t]}, {cstr(key)}, {cstr(section)}, {cstr(label)}, {cstr(help_)}, {mn}f, {mx}f, {step}f, {dflt}f, {decimals}, {nopts}, {cstr(options)}, '
            f'{ctrl}, {neg}, {{ {", ".join(map(str, ors))} }}, {{ {", ".join(map(str, ands))} }}, {skip}, Hidden::{hidden or "None"} }},'
        )
    pages.append((text(page["pageDisplayName"]), rows))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_menu_table.py from Valhalla Combat's MCM Helper config. Do not edit by hand.\n#pragma once\n\n")
    f.write("namespace VCMenu\n{\n")
    f.write("\tenum class Kind { Header, Toggle, Slider, Key, Enum, Text, Hidden };\n")
    f.write("\tenum class Hidden { None, TrueHudApi, TrueHudSpecialMeter, EldenCounterDamage, EldenCounterNpc };\n")
    f.write("\tstruct Entry\n\t{\n\t\tKind kind; const char* key; const char* section; const char* label; const char* help;\n")
    f.write("\t\tfloat min; float max; float step; float def; int decimals; int optionCount; const char* options;\n")
    f.write("\t\tint control; int condNot; int condOr[3]; int condAnd[3]; int skip; Hidden hidden;\n\t};\n")
    f.write("\tstruct Page { const char* name; const Entry* entries; int count; };\n\n")
    for i, (name, rows) in enumerate(pages):
        f.write(f"\tinline constexpr Entry kPage{i}[] = {{\n" + "\n".join(rows) + "\n\t};\n\n")
    f.write("\tinline constexpr Page kPages[] = {\n")
    for i, (name, rows) in enumerate(pages):
        f.write(f'\t\t{{ {cstr(name)}, kPage{i}, {len(rows)} }},\n')
    f.write("\t};\n}\n")
print("wrote", OUT, [(n, len(r)) for n, r in pages])
